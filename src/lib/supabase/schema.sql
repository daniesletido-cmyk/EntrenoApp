-- ==============================================================================
-- TRIGGER AUTOMÁTICO AL REGISTRARSE UN NUEVO USUARIO EN SUPABASE AUTH
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
  extracted_name TEXT;
  initial_role TEXT;
BEGIN
  extracted_name := COALESCE(
    NEW.raw_user_meta_data->>'full_name',
    NEW.raw_user_meta_data->>'name',
    SPLIT_PART(NEW.email, '@', 1)
  );

  -- Si el correo coincide con el del administrador/propietario
  IF LOWER(NEW.email) = 'danielespinosa@entrenoapp.es' OR LOWER(NEW.email) LIKE '%espinosa%' THEN
    initial_role := 'owner';
  ELSE
    initial_role := 'athlete';
  END IF;

  INSERT INTO public.profiles (
    id,
    email,
    full_name,
    role,
    webhook_token,
    onboarded
  )
  VALUES (
    NEW.id,
    NEW.email,
    extracted_name,
    initial_role,
    encode(gen_random_bytes(24), 'hex'),
    -- Si es el propietario original, considerarlo pre-configurado
    (initial_role = 'owner')
  )
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email,
    updated_at = NOW();

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- ==============================================================================
-- FUNCIÓN DE MIGRACIÓN HISTÓRICA: VINCULAR DATOS EXISTENTES A DANIEL ESPINOSA
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.migrate_owner_data(owner_user_id UUID)
RETURNS VOID AS $$
BEGIN
  -- 1. Asegurar rol owner en profiles
  UPDATE public.profiles
  SET role = 'owner',
      full_name = 'Daniel Espinosa',
      vam_pace = '3:59',
      vam_sec_km = 239,
      target_distance = 'Maratón',
      target_date = '2027-04-26',
      onboarded = TRUE
  WHERE id = owner_user_id;

  -- 2. Asignar entrenamientos huérfanos o sin user_id al propietario
  UPDATE public.workouts
  SET user_id = owner_user_id
  WHERE user_id IS NULL;

  -- 3. Asignar registros de sueño huérfanos
  UPDATE public.sleep_records
  SET user_id = owner_user_id
  WHERE user_id IS NULL;

  -- 4. Asignar mediciones biométricas
  UPDATE public.biometrics
  SET user_id = owner_user_id
  WHERE user_id IS NULL;

  -- 5. Asignar zapatillas
  UPDATE public.shoes
  SET user_id = owner_user_id
  WHERE user_id IS NULL;

  -- 6. Asignar objetivos
  UPDATE public.goals
  SET user_id = owner_user_id
  WHERE user_id IS NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
