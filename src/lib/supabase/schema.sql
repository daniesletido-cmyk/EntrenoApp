-- 2. TABLA DE PERFILES DE USUARIO (PROFILES)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  full_name TEXT,
  avatar_url TEXT,
  role TEXT NOT NULL DEFAULT 'athlete', -- 'athlete' | 'coach' | 'owner'
  
  -- Parámetros Fisiológicos y VAM
  weight_kg NUMERIC,
  resting_hr NUMERIC,
  max_hr NUMERIC,
  vam_pace TEXT DEFAULT '3:59',
  vam_sec_km NUMERIC DEFAULT 239,
  
  -- Objetivos y Planificación
  target_distance TEXT DEFAULT 'Maratón', -- '10K' | '21K' | '42K' | 'Fitness'
  target_date DATE,
  target_pace TEXT,
  days_per_week INTEGER DEFAULT 4,
  disciplines JSONB DEFAULT '["carrera", "crossfit", "fuerza"]'::jsonb,
  
  -- Conector Universal y Webhook Personal
  webhook_token TEXT UNIQUE DEFAULT encode(gen_random_bytes(24), 'hex'),
  
  -- Estado de Onboarding
  onboarded BOOLEAN NOT NULL DEFAULT FALSE,
  
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_profiles_email ON public.profiles(email);
