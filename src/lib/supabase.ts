/**
 * Guarda o actualiza una sesión en Supabase
 */
export async function upsertSessionToSupabase(session: SessionRow): Promise<boolean> {
  const sb = getSupabase();
  if (!sb) return false;

  try {
    const payload = {
      client_id: session.id,
      date: session.date,
      week_start: session.week_start,
      discipline: session.discipline,
      planned_code: session.planned_code,
      is_long_run: Boolean(session.is_long_run),
      is_extra: Boolean(session.is_extra),
      status: session.status,
      rpe: session.rpe,
      duration_min: session.duration_min,
      distance_km: session.distance_km,
      notes: session.notes,
      user_notes: session.user_notes,
      fit_data: session.fit_data ? tryParseJson(session.fit_data) : null,
      fit_backup: session.fit_backup,
      updated_at: new Date().toISOString(),
    };

    // Si ya existe registro con client_id o fecha + disciplina, actualizarlo
    const { error } = await sb.from("workouts").upsert(
      { ...payload, id: session.id },
      { onConflict: "id" }
    );

    if (error) {
      console.warn("[Supabase] Error al upsert workout:", error.message);
      return false;
    }
    return true;
  } catch (err) {
    console.warn("[Supabase] Excepción en upsertSessionToSupabase:", err);
    return false;
  }
}

