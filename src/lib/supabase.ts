/**
 * Recupera sesiones desde Supabase
 */
export async function fetchSessionsFromSupabase(
  fromDate?: string,
  toDate?: string
): Promise<SessionRow[] | null> {
  const sb = getSupabase();
  if (!sb) return null;

  try {
    let query = sb.from("workouts").select("*").order("date", { ascending: true });
    if (fromDate) query = query.gte("date", fromDate);
    if (toDate) query = query.lte("date", toDate);

    const { data, error } = await query;
    if (error || !data) return null;

    return data.map((row) => ({
      id: Number(row.client_id || row.id),
      date: row.date,
      week_start: row.week_start,
      discipline: row.discipline,
      planned_code: row.planned_code,
      is_long_run: row.is_long_run ? 1 : 0,
      is_extra: row.is_extra ? 1 : 0,
      status: row.status,
      rpe: row.rpe ? Number(row.rpe) : null,
      duration_min: row.duration_min ? Number(row.duration_min) : null,
      distance_km: row.distance_km ? Number(row.distance_km) : null,
      notes: row.notes,
      user_notes: row.user_notes,
      fit_backup: row.fit_backup,
      fit_data: row.fit_data ? JSON.stringify(row.fit_data) : null,
      created_at: row.created_at,
      updated_at: row.updated_at,
    })) as SessionRow[];
  } catch {
    return null;
  }
}

